CREATE OR REPLACE VIEW public.v_booking_status_counts AS
SELECT status, count(*) AS bookings
FROM public.bookings
GROUP BY status;

CREATE OR REPLACE VIEW public.v_dashboard_summary AS
SELECT
  (SELECT count(*) FROM public.bookings) AS bookings,
  (SELECT count(*) FROM public.bookings WHERE status = 'pending') AS incoming_bookings,
  (SELECT count(*) FROM public.bookings WHERE status = 'return_requested') AS pending_returns,
  (SELECT count(*) FROM public.vehicles WHERE deleted_at IS NULL) AS vehicles,
  (SELECT count(*) FROM public.users WHERE role = 'customer') AS customers,
  (SELECT count(*) FROM public.drivers WHERE status = 'active' AND deleted_at IS NULL) AS active_drivers,
  (SELECT count(*) FROM public.maintenances WHERE finished = false) AS open_maintenance,
  (SELECT count(*) FROM public.message_threads WHERE unread_staff = true) AS unread_threads,
  (SELECT COALESCE(sum(total), 0) FROM public.bookings
    WHERE payment_status = 'paid' AND status NOT IN ('rejected', 'cancelled')) AS revenue;

CREATE OR REPLACE VIEW public.v_fleet_repair_stats AS
SELECT
  count(*) AS total_vehicles,
  count(*) FILTER (WHERE status = 'maintenance') AS in_repair,
  COALESCE(round(100.0 * count(*) FILTER (WHERE status = 'maintenance') / NULLIF(count(*), 0)), 0) AS repair_percent
FROM public.vehicles
WHERE deleted_at IS NULL;

CREATE OR REPLACE VIEW public.v_registration_renewals_due AS
SELECT r.registration_id, r.vehicle_id, v.name, r.plate_number, r.next_reg_renewal,
       (r.next_reg_renewal - CURRENT_DATE) AS days_left
FROM public.vehicle_registrations r
JOIN public.vehicles v ON v.vehicle_id = r.vehicle_id
WHERE v.deleted_at IS NULL;

CREATE OR REPLACE VIEW public.v_revenue_by_vehicle_type AS
SELECT v.type, sum(b.total) AS revenue, count(*) AS paid_bookings
FROM public.bookings b
JOIN public.vehicles v ON v.vehicle_id = b.vehicle_id
WHERE b.payment_status = 'paid' AND b.status NOT IN ('rejected', 'cancelled')
GROUP BY v.type;

CREATE OR REPLACE VIEW public.v_vehicle_latest_prediction AS
SELECT prediction_id, vehicle_id, telemetry_id, target, prediction, needs_maintenance,
       probability, model_name, predicted_by, predicted_at
FROM (
  SELECT mp.*, row_number() OVER (
    PARTITION BY mp.vehicle_id, mp.target ORDER BY mp.predicted_at DESC, mp.prediction_id DESC
  ) AS rn
  FROM public.maintenance_predictions mp
) p
WHERE rn = 1;

CREATE OR REPLACE VIEW public.v_vehicle_latest_telemetry AS
SELECT *
FROM (
  SELECT tr.*, row_number() OVER (
    PARTITION BY tr.vehicle_id ORDER BY tr.created_at DESC, tr.telemetry_id DESC
  ) AS rn
  FROM public.telemetry_readings tr
) t
WHERE rn = 1;

CREATE OR REPLACE VIEW public.v_vehicle_rating_summary AS
SELECT v.vehicle_id, v.code, count(r.rating_id) AS rating_count,
       COALESCE(round(avg(r.stars), 1), 0) AS rating_average
FROM public.vehicles v
LEFT JOIN public.ratings r ON r.vehicle_id = v.vehicle_id
WHERE v.deleted_at IS NULL
GROUP BY v.vehicle_id, v.code;


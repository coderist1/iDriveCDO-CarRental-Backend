  CONSTRAINT ck_bookings_payment_status CHECK (payment_status IN ('unpaid', 'paid')),
  CONSTRAINT ck_bookings_ref CHECK (ref ~* '^IDR-[0-9]{8}-[0-9A-F]{3,6}$'),
  CONSTRAINT ck_bookings_status CHECK (status IN ('pending', 'confirmed', 'ongoing', 'return_requested', 'completed', 'rejected', 'cancelled')),

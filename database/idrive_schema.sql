CREATE OR REPLACE FUNCTION public.set_updated_at()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $function$;

CREATE OR REPLACE FUNCTION public.fn_bookings_before_insert()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
DECLARE
  v_capacity INTEGER;
  v_role     TEXT;
BEGIN
  SELECT capacity INTO v_capacity FROM vehicles WHERE vehicle_id = NEW.vehicle_id;
  IF NEW.number_of_passengers > v_capacity THEN
    RAISE EXCEPTION 'Passengers exceed this vehicle''s capacity.';
  END IF;

  SELECT role INTO v_role FROM users WHERE user_id = NEW.user_id;
  IF v_role <> 'customer' THEN
    RAISE EXCEPTION 'Bookings must belong to a customer account.';
  END IF;
  RETURN NEW;
END $function$;

CREATE OR REPLACE FUNCTION public.fn_bookings_before_update()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
BEGIN
  IF NEW.status <> OLD.status AND NOT (
       (OLD.status = 'pending'          AND NEW.status IN ('confirmed','rejected','cancelled'))
    OR (OLD.status = 'confirmed'        AND NEW.status IN ('ongoing','cancelled','return_requested'))
    OR (OLD.status = 'ongoing'          AND NEW.status IN ('completed','return_requested'))
    OR (OLD.status = 'return_requested' AND NEW.status IN ('completed','ongoing'))
  ) THEN
    RAISE EXCEPTION 'That status change is not allowed.';
  END IF;
  RETURN NEW;
END $function$;

CREATE OR REPLACE FUNCTION public.fn_drivers_before_write()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
DECLARE
  v_role TEXT;
BEGIN
  IF NEW.user_id IS NOT NULL THEN
    SELECT role INTO v_role FROM users WHERE user_id = NEW.user_id;
    IF v_role <> 'driver' THEN
      RAISE EXCEPTION 'Linked login must have the driver role.';
    END IF;
  END IF;
  RETURN NEW;
END $function$;

CREATE OR REPLACE FUNCTION public.fn_payments_before_insert()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
DECLARE
  v_status TEXT;
BEGIN
  SELECT status INTO v_status FROM bookings WHERE booking_id = NEW.booking_id;
  IF v_status IN ('cancelled','rejected') THEN
    RAISE EXCEPTION 'This booking cannot be paid.';
  END IF;
  RETURN NEW;
END $function$;

CREATE OR REPLACE FUNCTION public.fn_ratings_before_insert()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
DECLARE
  b_status  TEXT;
  b_user    BIGINT;
  b_vehicle BIGINT;
BEGIN
  SELECT status, user_id, vehicle_id INTO b_status, b_user, b_vehicle
  FROM bookings WHERE booking_id = NEW.booking_id;

  IF b_status <> 'completed' THEN
    RAISE EXCEPTION 'Rate the car after the trip is completed.';
  END IF;
  IF b_user <> NEW.user_id THEN
    RAISE EXCEPTION 'Only the renter can rate this car.';
  END IF;
  IF b_vehicle <> NEW.vehicle_id THEN
    RAISE EXCEPTION 'Rating vehicle must match the booked vehicle.';
  END IF;
  RETURN NEW;
END $function$;


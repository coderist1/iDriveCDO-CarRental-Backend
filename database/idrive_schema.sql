  CONSTRAINT fk_bookings_pickup FOREIGN KEY (pickup_location_id) REFERENCES public.locations (location_id),
  CONSTRAINT fk_bookings_dropoff FOREIGN KEY (dropoff_location_id) REFERENCES public.locations (location_id),
  CONSTRAINT fk_bookings_started_by FOREIGN KEY (started_by) REFERENCES public.users (user_id),
  CONSTRAINT fk_bookings_return_requested_by FOREIGN KEY (return_requested_by) REFERENCES public.users (user_id),
  CONSTRAINT fk_bookings_returned_by FOREIGN KEY (returned_by) REFERENCES public.users (user_id),
  CONSTRAINT ck_bookings_chauffeur CHECK ((drive_mode = 'chauffeur' AND driver_id IS NOT NULL) OR (drive_mode = 'self' AND driver_id IS NULL)),
  CONSTRAINT ck_bookings_confirmed_paid CHECK (status NOT IN ('confirmed', 'ongoing', 'return_requested', 'completed') OR payment_status = 'paid'),
  CONSTRAINT ck_bookings_dates CHECK (end_date > start_date),
  CONSTRAINT ck_bookings_days CHECK (days >= 1 AND days <= 30 AND days = (end_date - start_date)),
  CONSTRAINT ck_bookings_drive_mode CHECK (drive_mode IN ('self', 'chauffeur')),
  CONSTRAINT ck_bookings_fuel_before CHECK (fuel_before_rent IN ('Full', '3/4', '1/2', '1/4', 'Reserve', 'Empty')),

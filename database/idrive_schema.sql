  total                numeric(10,2) NOT NULL,
  status               varchar(20)   NOT NULL DEFAULT 'pending',
  payment_status       varchar(10)   NOT NULL DEFAULT 'unpaid',
  payment_method       varchar(10),
  notes                varchar(240),
  return_notes         varchar(240),
  date_reserve         timestamptz   NOT NULL DEFAULT now(),
  started_at           timestamptz,
  started_by           bigint,
  return_requested_at  timestamptz,
  return_requested_by  bigint,
  returned_at          timestamptz,
  returned_by          bigint,
  created_at           timestamptz   NOT NULL DEFAULT now(),
  updated_at           timestamptz   NOT NULL DEFAULT now(),
  CONSTRAINT bookings_pkey PRIMARY KEY (booking_id),
  CONSTRAINT uq_bookings_code UNIQUE (code),
  CONSTRAINT uq_bookings_ref UNIQUE (ref),
  CONSTRAINT fk_bookings_user FOREIGN KEY (user_id) REFERENCES public.users (user_id),
  CONSTRAINT fk_bookings_vehicle FOREIGN KEY (vehicle_id) REFERENCES public.vehicles (vehicle_id),
